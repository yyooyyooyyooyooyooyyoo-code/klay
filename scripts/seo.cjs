// llms.txt (https://llmstxt.org)
// ---------------------------------------------------------------------------------------------

function markdownText(value) {
  return String(value).replace(/\s+/g, ' ').trim().replace(/([\\[\]])/g, '\\$1');
}

function llmsLine(route) {
  const seo = getPageSeo(route.path);
  const title = seo.title.replace(/\s*\|\s*Klay Consultants$/i, '') || seo.title;
  return `- [${markdownText(title)}](${seo.canonical}): ${markdownText(seo.description)}`;
}

function buildLlmsTxt() {
  const routes = getPublicSeoRoutes();
  const optionalPaths = new Set([ROUTES.privacy, ROUTES.terms]);
  const pages = routes.filter((route) => route.source === 'page');
  const section = (title, list) => (list.length ? ['', `## ${title}`, '', ...list.map(llmsLine)] : []);
  return [
    '# Klay Consultants',
    '',
    `> ${markdownText(getPageSeo(ROUTES.home).description)}`,
    ...section('Pages', pages.filter((route) => !optionalPaths.has(route.path))),
    ...section('Services', routes.filter((route) => route.source === 'service')),
    ...section('Blog', routes.filter((route) => route.source === 'article')),
    ...section('Optional', pages.filter((route) => optionalPaths.has(route.path))),
    '',
  ].join('\n');
}

