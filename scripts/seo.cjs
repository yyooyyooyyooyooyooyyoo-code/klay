/**
 * mod_rewrite pattern for a decoded URL path (no leading slash). mod_rewrite matches the decoded path,
 * but each reserved or non-ASCII character also accepts its percent-encoded form in case a server
 * matches the raw path. Spaces become \x20 so the pattern never contains whitespace (no quoting needed).
 */
function htaccessPattern(decodedPath) {
  let pattern = '';
  for (const character of decodedPath) {
    if (/[A-Za-z0-9_~/-]/.test(character)) {
      pattern += character;
      continue;
    }
    const code = character.codePointAt(0);
    let literal = character;
    if (code <= 0x20 || code === 0x7f) literal = `\\x${code.toString(16).padStart(2, '0')}`;
    else if (/[\\^$.|?*+()[\]{}"]/.test(character)) literal = `\\${character}`;
    const encoded = encodeURIComponent(character);
    pattern += encoded === character
      ? literal
      : `(?:${[...new Set([literal, encoded, encoded.toLowerCase()])].join('|')})`;
  }
  return pattern;
}

function htaccessRedirectLine(rule) {
  const from = decodePath(rule.from).replace(/^\/+/, '').replace(/\/+$/, '');
  // The target is written as is: % and $ would be read as back-references, and spaces would split it.
  if (!/^\/[A-Za-z0-9._~/-]*$/.test(rule.to)) throw new Error(`Redirect target ${rule.to} needs escaping for .htaccess`);
  return `RewriteRule ^/?${htaccessPattern(from)}/?$ ${rule.to} [R=301,L]`;
}

function htaccessFolderFile(folder, cacheControl) {
  return [
    `${GENERATED_MARK} - do not edit by hand.`,
    `# Cache-Control for /${folder}/ on Apache/LiteSpeed (Hostinger). See docs/DEPLOY-HOSTINGER.md.`,
    '<IfModule mod_headers.c>',
    `  Header set Cache-Control "${cacheControl}"`,
    '</IfModule>',
    '',
  ].join('\n');
}

function buildHtaccess(redirects) {
  const host = CANONICAL_HOST.replace(/\./g, '\\.');
  const header = (name, value) => `  Header always set ${name} "${value}"`;
  return [
    `${GENERATED_MARK} - do not edit by hand (run \`npm run build\`).`,
    '# Apache/LiteSpeed configuration for the static site on Hostinger (upload with the rest of dist/).',
    '# Redirects come from the same list as dist/_redirects (Netlify preview and server.js). The .htaccess',
    `# files in ${Object.keys(HTACCESS_FOLDER_CACHE).map((folder) => `${folder}/`).join(', ')} set those folders' Cache-Control.`,
    '# See docs/DEPLOY-HOSTINGER.md.',
    '',
    '# index.html first, so a leftover WordPress index.php can never answer for a folder.',
    'DirectoryIndex index.html',
    'Options -Indexes',
    'ErrorDocument 404 /404.html',
    '',
    '<IfModule mod_mime.c>',
    '  AddType application/manifest+json .webmanifest',
    '  AddType image/webp .webp',
    '  AddType image/avif .avif',
    '  AddType font/woff2 .woff2',
    '  AddType video/mp4 .mp4',
    '  AddCharset utf-8 .html .css .js .json .xml .txt .webmanifest .svg',
    '</IfModule>',
    '',
    '<IfModule mod_rewrite.c>',
    '  RewriteEngine On',
    '  RewriteBase /',
    '',
    '  # SSL certificate validation and other /.well-known/ files: served as they are.',
    '  RewriteRule ^/?\\.well-known/ - [L]',
    '',
    `  # http:// and www. go to https://${CANONICAL_HOST} in one 301. Other host names (for example a`,
    '  # temporary hosting domain) are left alone. X-Forwarded-Proto covers a CDN that connects over http.',
    `  RewriteCond %{HTTP_HOST} ^www\\.${host}\\.?(?::[0-9]+)?$ [NC]`,
    `  RewriteRule ^ https://${CANONICAL_HOST}%{REQUEST_URI} [R=301,L]`,
    `  RewriteCond %{HTTP_HOST} ^${host}\\.?(?::[0-9]+)?$ [NC]`,
    '  RewriteCond %{HTTPS} off',
    '  RewriteCond %{HTTP:X-Forwarded-Proto} !https [NC]',
    `  RewriteRule ^ https://${CANONICAL_HOST}%{REQUEST_URI} [R=301,L]`,
    '',
    '  # /index.html and /<path>/index.html duplicate the folder URL: 301 to /<path>/. THE_REQUEST is the',
    '  # original request line, so the DirectoryIndex subrequest for /<path>/ never matches (no loop).',
    '  RewriteCond %{THE_REQUEST} \\s/+((?:[^?\\s]*/)?)index\\.html[?\\s] [NC]',
    '  RewriteRule (?:^|/)index\\.html$ /%1 [NC,R=301,L]',
    '',
    '  # Hidden files (.htaccess, .git, .env ...) and Netlify config files are not public.',
    '  RewriteRule (?:^|/)\\.(?!well-known(?:/|$)) - [F,L]',
    '  RewriteRule ^/?_(?:redirects|headers)$ - [F,L]',
    '',
    '  # Old WordPress endpoints: 410 Gone (this site has no PHP, no wp-admin and no REST API).',
    '  RewriteRule ^/?(?:wp-admin|wp-includes|wp-json)(?:/|$) - [G,L]',
    '  RewriteRule \\.php$ - [G,L]',
    '',
    '  # Moved pages, renamed articles and legacy image URLs (from src/content/blog/posts.ts,',
    '  # scripts/legacy-image-redirects.json and the route aliases in scripts/seo.cjs).',
    ...redirects.map((rule) => `  ${htaccessRedirectLine(rule)}`),
    '',
    '  # Old WordPress archives, feeds and root pagination /page/N/ (/blog/page/N/ are real pages here):',
    '  # the blog index, query string dropped.',
    '  RewriteRule ^/?(?:category|tag|author)(?:/.*)?$ /blog/? [R=301,L]',
    '  RewriteRule ^/?(?:.+/)?feed(?:/.*)?$ /blog/? [R=301,L]',
    '  RewriteRule ^/?page/[0-9]+/?$ /blog/? [R=301,L]',
    '  # Old WordPress sitemaps (SEO plugin sitemap_index.xml, post-sitemap.xml, page-sitemap2.xml ...;',
    '  # core wp-sitemap*.xml): the new sitemap index. Mirrored in server.js.',
    `  RewriteRule ^/?${OLD_WORDPRESS_SITEMAP_PATTERN}$ /sitemap.xml [R=301,L]`,
    '</IfModule>',
    '',
    '<IfModule mod_headers.c>',
    ...Object.entries(SECURITY_HEADERS).map(([name, value]) => header(name, value)),
    '',
    '  # Cache-Control by file name. assets/ (1 year, hashed names), images/, videos/ and fonts/ (30 days)',
    '  # are set by the .htaccess file inside each folder.',
    '  <FilesMatch "\\.html$">',
    `    Header set Cache-Control "${CACHE.html}"`,
    '  </FilesMatch>',
    '  <FilesMatch "^(?:sitemap[^/]*\\.xml|robots\\.txt|llms\\.txt)$">',
    `    Header set Cache-Control "${CACHE.short}"`,
    '  </FilesMatch>',
    '  <FilesMatch "^(?:favicon\\.ico|favicon-48\\.png|apple-touch-icon\\.png|icon-[0-9]+\\.png|site\\.webmanifest)$">',
    `    Header set Cache-Control "${CACHE.icons}"`,
    '  </FilesMatch>',
    '</IfModule>',
    '',
    '# Compression (LiteSpeed also compresses text responses on its own).',
    '<IfModule mod_brotli.c>',
    '  <IfModule mod_filter.c>',
    `    AddOutputFilterByType BROTLI_COMPRESS ${COMPRESSIBLE_TYPES}`,
    '  </IfModule>',
    '</IfModule>',
    '<IfModule mod_deflate.c>',
    '  <IfModule mod_filter.c>',
    `    AddOutputFilterByType DEFLATE ${COMPRESSIBLE_TYPES}`,
    '  </IfModule>',
    '</IfModule>',
    '',
  ].join('\n');
}

/**
 * Copies public/.htaccess into dist/ if Vite did not, and writes the per-folder .htaccess files.
 * Called by scripts/prerender.mjs after `vite build` (dist/assets/ only exists then).
 */
function writeDistHtaccess(targetDir = distDir) {
  const rootFile = path.join(targetDir, '.htaccess');
  if (!fs.existsSync(rootFile)) fs.copyFileSync(path.join(publicDir, '.htaccess'), rootFile);
  const written = ['.htaccess'];
  for (const [folder, cacheControl] of Object.entries(HTACCESS_FOLDER_CACHE)) {
    const folderPath = path.join(targetDir, folder);
    if (!fs.existsSync(folderPath)) continue;
    fs.writeFileSync(path.join(folderPath, '.htaccess'), htaccessFolderFile(folder, cacheControl));
    written.push(`${folder}/.htaccess`);
  }
  return written;
}

