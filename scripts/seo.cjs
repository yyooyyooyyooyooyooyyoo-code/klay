function validateSitemapFile(name, errors) {
  const file = path.join(distDir, name);
  if (!fs.existsSync(file)) {
    errors.push(`Missing dist/${name}`);
    return undefined;
  }
  const content = fs.readFileSync(file, 'utf8');
  const source = path.join(publicDir, name);
  if (fs.existsSync(source) && fs.readFileSync(source, 'utf8') !== content) {
    errors.push(`dist/${name} differs from public/${name} (stale build output)`);
  }
  if (!content.startsWith('<?xml version="1.0" encoding="UTF-8"?>')) errors.push(`${name}: missing XML declaration`);
  if (!new RegExp(`<(?:urlset|sitemapindex)\\b[^>]*xmlns="${SITEMAP_XMLNS.replace(/[./]/g, '\\$&')}"`).test(content)) {
    errors.push(`${name}: invalid sitemap root namespace`);
  }
  if ((content.match(/<loc>/g) || []).length !== (content.match(/<\/loc>/g) || []).length) {
    errors.push(`${name}: unbalanced loc elements`);
  }
  for (const match of content.matchAll(/<(loc|image:loc)>(.*?)<\/\1>/g)) {
    let url;
    try {
      url = new URL(match[2].replace(/&amp;/g, '&'));
    } catch {
      errors.push(`${name}: invalid URL ${match[2]}`);
      continue;
    }
    if (url.origin !== SITE_ORIGIN) errors.push(`${name}: URL outside ${SITE_ORIGIN}: ${url.href}`);
    if (!/^[\x21-\x7e]+$/.test(match[2])) errors.push(`${name}: URL is not percent-encoded: ${match[2]}`);
  }
  for (const match of content.matchAll(/<lastmod>(.*?)<\/lastmod>/g)) {
    if (!isCalendarDate(match[1])) errors.push(`${name}: invalid lastmod ${match[1]}`);
    else if (match[1] > LATEST_ALLOWED_DATE) errors.push(`${name}: lastmod ${match[1]} is in the future`);
  }
  return content;
}

/** dist file paths (relative, '/'-separated), skipping hidden files and folders. */
function listDistFiles(dir = distDir, prefix = '') {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const relative = `${prefix}${entry.name}`;
    if (entry.isDirectory()) files.push(...listDistFiles(path.join(dir, entry.name), `${relative}/`));
    else files.push(relative);
  }
  return files;
}

/**
 * Checks dist/.htaccess against dist/_redirects by running its RewriteRules (those without a
 * RewriteCond, in file order, as mod_rewrite would) on every redirect source, prerendered page and file.
 */
function validateHtaccess(redirectsContent, errors) {
  const file = path.join(distDir, '.htaccess');
  if (!fs.existsSync(file)) {
    errors.push('Missing dist/.htaccess (Hostinger redirects, headers and caching)');
    return;
  }
  const content = fs.readFileSync(file, 'utf8');
  const source = path.join(publicDir, '.htaccess');
  if (!content.startsWith(GENERATED_MARK)) errors.push('dist/.htaccess is not the generated file');
  if (fs.existsSync(source) && fs.readFileSync(source, 'utf8') !== content) errors.push('dist/.htaccess differs from public/.htaccess (stale build output)');
  for (const required of ['DirectoryIndex index.html', 'ErrorDocument 404 /404.html', 'RewriteEngine On', 'Header always set Strict-Transport-Security']) {
    if (!content.includes(required)) errors.push(`dist/.htaccess is missing "${required}"`);
  }
  for (const folder of Object.keys(HTACCESS_FOLDER_CACHE)) {
    if (fs.existsSync(path.join(distDir, folder)) && !fs.existsSync(path.join(distDir, folder, '.htaccess'))) {
      errors.push(`Missing dist/${folder}/.htaccess (Cache-Control for /${folder}/)`);
    }
  }

  const rules = [];
  let conditioned = false;
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.startsWith('RewriteCond ')) conditioned = true;
    if (!trimmed.startsWith('RewriteRule ')) continue;
    const [, pattern, target, flags = ''] = trimmed.split(/\s+/);
    if (!conditioned) {
      try {
        rules.push({ line: trimmed, regex: new RegExp(pattern), target, flags });
      } catch (error) {
        errors.push(`dist/.htaccess: invalid pattern in "${trimmed}" (${error.message})`);
      }
    }
    conditioned = false;
  }
  const firstMatch = (subject) => rules.find((rule) => rule.regex.test(subject));

  for (const line of redirectsContent.split(/\r?\n/)) {
    const [from, to] = line.trim().split(/\s+/);
    if (!from || from.startsWith('#') || !to) continue;
    if (!content.includes(htaccessRedirectLine({ from, to }))) errors.push(`dist/.htaccess is missing the redirect ${from} -> ${to}`);
    const decoded = decodePath(from).replace(/^\/+/, '').replace(/\/+$/, '');
    const raw = from.replace(/^\/+/, '').replace(/\/+$/, '');
    for (const subject of new Set([decoded, `${decoded}/`, raw])) {
      const rule = firstMatch(subject);
      if (!rule || rule.target !== to || rule.flags !== '[R=301,L]') {
        errors.push(`dist/.htaccess: /${subject} should 301 to ${to} but ${rule ? `matches "${rule.line}"` : 'matches no rule'}`);
      }
    }
  }
  const pages = getPrerenderRoutes().map((route) => route.path.replace(/^\/+/, ''));
  const files = listDistFiles().filter((name) => !/^_(?:redirects|headers)$/.test(name));
  for (const subject of [...pages, ...files]) {
    const rule = firstMatch(subject);
    if (rule) errors.push(`dist/.htaccess: /${subject} exists but matches "${rule.line}"`);
  }
}

function validateLlmsTxt(knownPaths, errors) {
  const file = path.join(distDir, 'llms.txt');
  if (!fs.existsSync(file)) {
    errors.push('Missing dist/llms.txt');
    return;
  }
  const content = fs.readFileSync(file, 'utf8');
  const source = path.join(publicDir, 'llms.txt');
  if (fs.existsSync(source) && fs.readFileSync(source, 'utf8') !== content) errors.push('dist/llms.txt differs from public/llms.txt (stale build output)');
  if (!/^# Klay Consultants\n\n> \S/.test(content)) errors.push('llms.txt must start with "# Klay Consultants" and a "> " summary');
  const links = Array.from(content.matchAll(/^- \[.+?\]\((\S+?)\): \S/gm), (match) => match[1]);
  if (links.length !== getPublicSeoRoutes().length) errors.push(`llms.txt lists ${links.length} links for ${getPublicSeoRoutes().length} public routes`);
  for (const link of links) {
    if (!link.startsWith(`${SITE_ORIGIN}/`) || !knownPaths.has(routeKey(decodePath(new URL(link).pathname)))) {
      errors.push(`llms.txt: ${link} is not a public page`);
    }
  }
}

function locsIn(content) {
  return Array.from(content.matchAll(/<loc>(.*?)<\/loc>/g), (match) => match[1].replace(/&amp;/g, '&'));
}

function validateBuild() {
  const routes = getPublicSeoRoutes();
  const knownPaths = new Set(getPrerenderRoutes().map((route) => routeKey(route.path)));
  const canonicals = new Set();
  const titles = new Set();
  const descriptions = new Set();
  const pageHtml = new Map();
  const errors = [];
  const warnings = [];

  for (const route of routes) {
    const seo = getPageSeo(route.path);
    if (!seo.title.trim()) errors.push(`${route.path}: title is empty`);
    if (!seo.description.trim()) errors.push(`${route.path}: description is empty`);
    if (canonicals.has(seo.canonical)) errors.push(`${route.path}: duplicate canonical ${seo.canonical}`);
    if (titles.has(seo.title.toLowerCase())) errors.push(`${route.path}: duplicate title`);
    if (descriptions.has(seo.description.toLowerCase())) errors.push(`${route.path}: duplicate description`);
    canonicals.add(seo.canonical);
    titles.add(seo.title.toLowerCase());
    descriptions.add(seo.description.toLowerCase());

    const outputPath = htmlPathFor(route.path);
    if (!fs.existsSync(outputPath)) {
      errors.push(`${route.path}: prerendered HTML is missing`);
      continue;
    }
    const html = fs.readFileSync(outputPath, 'utf8');
    pageHtml.set(seo.canonical, html);
    const head = html.slice(0, html.indexOf('</head>'));
    if (!head.includes(`<title>${xmlEscape(seo.title)}</title>`)) errors.push(`${route.path}: title missing from initial HTML`);
    if (!head.includes(`content="${xmlEscape(seo.description)}"`)) errors.push(`${route.path}: description missing from initial HTML`);
    if (!head.includes(`<link rel="canonical" href="${seo.canonical}" />`)) errors.push(`${route.path}: canonical missing from initial HTML`);
    if (!head.includes('<meta name="robots" content="index,follow" />')) errors.push(`${route.path}: public page is not indexable`);
    if (!html.includes('<div id="root" data-prerendered="true">')) errors.push(`${route.path}: page body was not prerendered`);
    if (seo.title.length > 70) warnings.push(`${route.path}: title is ${seo.title.length} characters (Google shows about 60)`);
    if (seo.description.length > 170) warnings.push(`${route.path}: description is ${seo.description.length} characters`);
    if (
      !head.includes('property="og:title"') ||
      !head.includes('property="og:description"') ||
      !head.includes(`<meta property="og:url" content="${seo.canonical}" />`) ||
      !head.includes('property="og:image"') ||
      !head.includes('name="twitter:card"')
    ) {
      errors.push(`${route.path}: Open Graph or Twitter metadata missing`);
    }
    const jsonLdMatch = head.match(/<script id="seo-jsonld" type="application\/ld\+json">([\s\S]*?)<\/script>/);
    if (!jsonLdMatch) {
      errors.push(`${route.path}: JSON-LD is missing from initial HTML`);
    } else {
      let jsonLd;
      try {
        jsonLd = JSON.parse(jsonLdMatch[1]);
      } catch {
        errors.push(`${route.path}: JSON-LD is invalid`);
      }
      const graph = Array.isArray(jsonLd?.['@graph']) ? jsonLd['@graph'] : [];
      if (jsonLd && !graph.some((node) => node['@type'] === 'WebPage' && node.url === seo.canonical)) {
        errors.push(`${route.path}: JSON-LD WebPage does not match the canonical URL`);
      }
      if (jsonLd && route.source === 'article') {
        const posting = graph.find((node) => node['@type'] === 'BlogPosting');
        if (!posting) errors.push(`${route.path}: BlogPosting JSON-LD is missing`);
        else {
          for (const field of ['headline', 'image', 'datePublished', 'dateModified']) {
            if (!posting[field]) errors.push(`${route.path}: BlogPosting.${field} is missing`);
          }
          if (posting.datePublished && !isCalendarDate(posting.datePublished)) errors.push(`${route.path}: BlogPosting.datePublished is invalid`);
        }
      }
    }
    const h1Count = (html.match(/<h1(?:\s|>)/gi) || []).length;
    if (h1Count !== 1) errors.push(`${route.path}: expected exactly one H1, found ${h1Count}`);
    const highPriorityImages = (html.match(/<img\b[^>]*\bfetchpriority="high"/gi) || []).length;
    if (highPriorityImages > 1) warnings.push(`${route.path}: ${highPriorityImages} images have fetchpriority="high" (use it for the LCP image only)`);
    for (const image of html.matchAll(/<img\b[^>]*>/gi)) {
      if (!/\balt\s*=/.test(image[0])) errors.push(`${route.path}: image is missing an alt attribute`);
      const src = image[0].match(/\bsrc="(\/[^/"][^"]*)"/);
      if (src && !fs.existsSync(path.join(distDir, decodePath(src[1].split(/[?#]/, 1)[0])))) {
        errors.push(`${route.path}: image file is missing: ${src[1]}`);
      }
    }
    for (const link of html.matchAll(/<a\b[^>]*\bhref="([^"]+)"/gi)) {
      const href = link[1];
      if (!href.startsWith('/') || href.startsWith('//')) continue;
      const pathOnly = routeKey(decodePath(href.split(/[?#]/, 1)[0]));
      if (path.posix.extname(pathOnly)) {
        if (!fs.existsSync(path.join(distDir, pathOnly))) errors.push(`${route.path}: link to a missing file ${href}`);
      } else if (!knownPaths.has(pathOnly)) {
        errors.push(`${route.path}: broken internal link ${href}`);
      }
    }
  }

  const sitemapIndex = validateSitemapFile('sitemap.xml', errors);
  const sitemapContents = new Map(SITEMAP_FILES.map((name) => [name, validateSitemapFile(name, errors)]));
  if (sitemapIndex) {
    const listed = locsIn(sitemapIndex);
    const expected = SITEMAP_FILES.map((name) => `${SITE_ORIGIN}/${name}`);
    if (listed.length !== expected.length || expected.some((url) => !listed.includes(url))) {
      errors.push(`sitemap.xml must list exactly: ${SITEMAP_FILES.join(', ')}`);
    }
  }
  for (const sitemap of URL_SITEMAPS) {
    const content = sitemapContents.get(sitemap.file);
    if (!content) continue;
    const urls = locsIn(content);
    if (new Set(urls).size !== urls.length) errors.push(`${sitemap.file} contains duplicate URLs`);
    const expectedUrls = routes.filter((route) => route.source === sitemap.source).map((route) => getPageSeo(route.path).canonical);
    if (urls.length !== expectedUrls.length || expectedUrls.some((url) => !urls.includes(url))) {
      errors.push(`${sitemap.file} does not match the public route registry`);
    }
  }
  const imageSitemap = sitemapContents.get(IMAGE_SITEMAP);
  if (imageSitemap) {
    for (const match of imageSitemap.matchAll(/<url><loc>(.*?)<\/loc>.*?<image:loc>(.*?)<\/image:loc>/g)) {
      const pageUrl = match[1].replace(/&amp;/g, '&');
      const imagePath = new URL(match[2].replace(/&amp;/g, '&')).pathname;
      const html = pageHtml.get(pageUrl);
      if (!html) errors.push(`${IMAGE_SITEMAP}: ${pageUrl} is not a public page`);
      else if (!html.includes(imagePath)) warnings.push(`${IMAGE_SITEMAP}: ${imagePath} is not shown on ${pageUrl}`);
      if (!fs.existsSync(path.join(distDir, decodePath(imagePath)))) errors.push(`${IMAGE_SITEMAP}: missing image file ${imagePath}`);
    }
  }

  const notFoundHtml = path.join(distDir, '404.html');
  if (!fs.existsSync(notFoundHtml)) errors.push('Missing generated 404.html');
  else {
    const notFound = fs.readFileSync(notFoundHtml, 'utf8');
    if (!notFound.includes('name="robots" content="noindex,follow"') || !notFound.includes('<h1>Page not found</h1>')) {
      errors.push('404.html must be noindex and include a visible not-found heading');
    }
    if (!notFound.includes('rel="icon"')) errors.push('404.html is missing the favicon links');
    if (notFound.includes('rel="canonical"')) errors.push('404.html must not declare a canonical URL');
  }
  const redirectsFile = path.join(distDir, '_redirects');
  if (!fs.existsSync(redirectsFile)) errors.push('Missing dist/_redirects');
  else validateHtaccess(fs.readFileSync(redirectsFile, 'utf8'), errors);
  validateLlmsTxt(knownPaths, errors);
  const robotsFile = path.join(distDir, 'robots.txt');
  const robots = fs.existsSync(robotsFile) ? fs.readFileSync(robotsFile, 'utf8') : '';
  if (
    !robots.includes('User-agent: *') ||
    !robots.includes('Allow: /') ||
    !robots.includes('Disallow: /api/') ||
    !robots.includes(`Sitemap: ${SITE_ORIGIN}/sitemap.xml`)
  ) {
    errors.push('robots.txt is missing the public crawl policy or sitemap URL');
  }
  if (warnings.length) console.warn(`SEO warnings:\n${warnings.map((warning) => `- ${warning}`).join('\n')}`);
  if (errors.length) {
    console.error(errors.map((error) => `- ${error}`).join('\n'));
    process.exitCode = 1;
    return;
  }
  console.log(`SEO validation passed for ${routes.length} prerendered public routes, sitemap files, metadata, headings, links, images and JSON-LD.`);
}

