function isCalendarDate(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === value;
}

function utcDate(offsetDays = 0) {
  const date = new Date();
  date.setUTCDate(date.getUTCDate() + offsetDays);
  return date.toISOString().slice(0, 10);
}

// Latest lastmod accepted: tomorrow in UTC, so an article dated "today" in Dubai (UTC+4) still
// passes on a build machine that runs on UTC.
const LATEST_ALLOWED_DATE = utcDate(1);

let gitHistoryState;
/** 'full' (dates from git log), 'shallow' (history incomplete: dates would be wrong) or 'none'. */
function gitHistory() {
  if (gitHistoryState === undefined) {
    try {
      const shallow = execFileSync('git', ['rev-parse', '--is-shallow-repository'], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
      gitHistoryState = shallow === 'true' ? 'shallow' : 'full';
    } catch {
      gitHistoryState = 'none';
    }
    if (gitHistoryState === 'shallow') {
      console.warn('Shallow git clone: lastmod is omitted for pages dated from git history (fetch the full history to include it).');
    }
  }
  return gitHistoryState;
}

/** Last commit date of a source file; its modification time outside a git checkout. */
function sourceFileDate(relativeFile) {
  const file = path.join(root, relativeFile);
  if (!fs.existsSync(file)) throw new Error(`Missing lastmod source: ${relativeFile}`);
  const history = gitHistory();
  if (history === 'shallow') return undefined;
  if (history === 'full') {
    try {
      const date = execFileSync('git', ['log', '-1', '--format=%cs', '--', relativeFile], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
      if (isCalendarDate(date)) return date;
    } catch {
      // fall through to the file time (for example a new, uncommitted file)
    }
  }
  return fs.statSync(file).mtime.toISOString().slice(0, 10);
}

/** Every article needs a parseable date: it feeds the sitemap lastmod and the JSON-LD dates. */
function checkArticleDates() {
  const errors = [];
  for (const post of BLOG_POSTS) {
    for (const field of ['date', 'updated']) {
      const value = post[field];
      if (field === 'updated' && value === undefined) continue;
      if (!isCalendarDate(toIsoDate(String(value)))) {
        errors.push(`${post.slug}: ${field} "${value}" is not a valid date in the form '11 Nov 2026'`);
      }
    }
  }
  if (errors.length) throw new Error(`Invalid article dates:\n${errors.map((error) => `- ${error}`).join('\n')}`);
}

function routeLastmod(route, newestArticleDate) {
  let date = route.lastmod;
  if (date !== undefined && !isCalendarDate(date)) throw new Error(`${route.path}: invalid lastmod "${date}"`);
  if (!date && route.lastmodSource) date = sourceFileDate(route.lastmodSource);
  // The blog index changes whenever an article is published or updated.
  if (route.path === ROUTES.blog && newestArticleDate && (!date || newestArticleDate > date)) date = newestArticleDate;
  if (date && date > LATEST_ALLOWED_DATE) {
    console.warn(`${route.path}: lastmod ${date} is in the future; using today's date in the sitemap.`);
    date = utcDate();
  }
  return date;
}

function maxDate(dates) {
  return dates.filter(Boolean).sort().at(-1);
}

