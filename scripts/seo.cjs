function writeXml(name, rootTag, rows) {
  const xml = ['<?xml version="1.0" encoding="UTF-8"?>', rootTag, ...rows, `</${rootTag.match(/^<([\w:]+)/)[1]}>`, ''].join('\n');
  fs.writeFileSync(path.join(publicDir, name), xml);
}

function urlRow(loc, lastmod, extra = '') {
  return `  <url><loc>${xmlEscape(loc)}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ''}${extra}</url>`;
}

/** Article cover images hosted on this site (Google only uses images from other hosts when both are verified). */
function imageSitemapEntries(entries) {
  return entries
    .filter((entry) => entry.route.source === 'article')
    .map((entry) => ({ ...entry, image: getPageSeo(entry.route.path).image }))
    .filter((entry) => entry.image.startsWith(`${SITE_ORIGIN}/`));
}

function generateSitemaps() {
  fs.mkdirSync(publicDir, { recursive: true });
  checkArticleDates();
  const routes = getPublicSeoRoutes();
  const entries = routes.map((route) => ({
    route,
    loc: getPageSeo(route.path).canonical,
    lastmod: route.source === 'article' ? routeLastmod(route) : undefined,
  }));
  const newestArticleDate = maxDate(entries.map((entry) => entry.lastmod));
  for (const entry of entries) {
    if (entry.route.source !== 'article') entry.lastmod = routeLastmod(entry.route, newestArticleDate);
  }

  const written = [];
  for (const sitemap of URL_SITEMAPS) {
    const sitemapEntries = entries.filter((entry) => entry.route.source === sitemap.source);
    writeXml(
      sitemap.file,
      `<urlset xmlns="${SITEMAP_XMLNS}">`,
      sitemapEntries.map((entry) => urlRow(entry.loc, entry.lastmod)),
    );
    written.push({ file: sitemap.file, lastmod: maxDate(sitemapEntries.map((entry) => entry.lastmod)) });
  }

  const imageEntries = imageSitemapEntries(entries);
  writeXml(
    IMAGE_SITEMAP,
    `<urlset xmlns="${SITEMAP_XMLNS}" xmlns:image="${IMAGE_XMLNS}">`,
    imageEntries.map((entry) => urlRow(
      entry.loc,
      entry.lastmod,
      `<image:image><image:loc>${xmlEscape(entry.image)}</image:loc></image:image>`,
    )),
  );
  written.push({ file: IMAGE_SITEMAP, lastmod: maxDate(imageEntries.map((entry) => entry.lastmod)) });

  writeXml(
    'sitemap.xml',
    `<sitemapindex xmlns="${SITEMAP_XMLNS}">`,
    written.map(({ file, lastmod }) => (
      `  <sitemap><loc>${SITE_ORIGIN}/${file}</loc>${lastmod ? `<lastmod>${lastmod}</lastmod>` : ''}</sitemap>`
    )),
  );
  fs.writeFileSync(path.join(publicDir, 'robots.txt'), ROBOTS_TXT);
  const redirects = writeRedirects();
  fs.writeFileSync(path.join(publicDir, '.htaccess'), buildHtaccess(redirects));
  fs.writeFileSync(path.join(publicDir, 'llms.txt'), buildLlmsTxt());
  removeStaleHeadersFile();
  console.log(
    `Generated sitemap index, ${routes.length} route entries (${BLOG_POSTS.length} articles, ${imageEntries.length} images), `
    + `${redirects.length} redirects (_redirects and .htaccess) and llms.txt.`,
  );
}

// ---------------------------------------------------------------------------------------------
// Redirects (_redirects, Netlify format; server.js applies the same file)
// ---------------------------------------------------------------------------------------------

function decodePath(value) {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

function writeRedirects() {
  const rules = [];
  const errors = [];
  const postSlugs = new Set(BLOG_POSTS.map((post) => post.slug));

  for (const [from, to] of Object.entries(BLOG_REDIRECTS)) {
    if (postSlugs.has(from)) errors.push(`BLOG_REDIRECTS: "${from}" is still a published article (its page would shadow the redirect)`);
    if (!postSlugs.has(to)) errors.push(`BLOG_REDIRECTS: target "${to}" (from "${from}") is not a published article`);
    rules.push({ from: `/blog/${from}`, to: getBlogArticleRoute(to) });
    if (isPublicRootPostSlug(from)) rules.push({ from: `/${from}`, to: getBlogArticleRoute(to) });
  }
  for (const post of BLOG_POSTS) {
    if (isPublicRootPostSlug(post.slug)) rules.push({ from: `/blog/${post.slug}`, to: `/${post.slug}/` });
  }
  for (const alias of ROUTE_ALIASES) {
    const target = canonicalizeInternalRoute(alias);
    if (routeKey(target) !== alias) rules.push({ from: alias, to: target });
  }
  for (const [from, to] of Object.entries(imageRedirects)) rules.push({ from, to });
  // Blog pagination: page 1 lives at /blog/ (BlogPage also redirects client-side).
  rules.push({ from: '/blog/page/1', to: '/blog/' });

  // Integrity: Netlify matches paths with or without a trailing slash, so compare without it.
  const knownRoutes = new Set(getPrerenderRoutes().map((route) => routeKey(route.path)));
  const sources = new Map();
  for (const rule of rules) {
    for (const value of [rule.from, rule.to]) {
      if (!value.startsWith('/') || value.startsWith('//') || /\s/.test(value)) errors.push(`Invalid redirect path "${value}"`);
    }
    const key = routeKey(decodePath(rule.from));
    if (sources.has(key)) errors.push(`Duplicate redirect source ${rule.from}`);
    sources.set(key, rule);
    if (knownRoutes.has(key)) errors.push(`Redirect source ${rule.from} is a prerendered page, so Netlify would never apply it`);
    if (path.posix.extname(key) && fs.existsSync(path.join(publicDir, key))) {
      errors.push(`Redirect source ${rule.from} is an existing file in public/, so Netlify would never apply it`);
    }
  }
  for (const rule of rules) {
    const target = routeKey(decodePath(rule.to));
    if (sources.has(target)) errors.push(`Redirect chain: ${rule.from} -> ${rule.to} -> ${sources.get(target).to}`);
    const exists = path.posix.extname(target)
      ? fs.existsSync(path.join(publicDir, target))
      : knownRoutes.has(target);
    if (!exists) errors.push(`Redirect target ${rule.to} (from ${rule.from}) does not exist`);
  }
  if (errors.length) throw new Error(`Invalid redirects:\n${[...new Set(errors)].map((error) => `- ${error}`).join('\n')}`);

  const lines = [`${GENERATED_MARK} - do not edit by hand.`, ...rules.map((rule) => `${rule.from}  ${rule.to}  301`)];
  fs.writeFileSync(path.join(publicDir, '_redirects'), `${lines.join('\n')}\n`);
  return rules;
}

/**
 * Earlier builds wrote a per-context public/_headers for Netlify previews. The whole Netlify site is now
 * noindex via netlify.toml, so remove a leftover generated copy (a hand-written _headers is kept).
 */
function removeStaleHeadersFile() {
  const file = path.join(publicDir, '_headers');
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').startsWith(GENERATED_MARK)) fs.unlinkSync(file);
}

